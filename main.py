ax5.set_title('Error Distribution', fontweight='bold')
ax5.legend()

# --- Graph 6: Naive Bayes & Logistic Regression Confusion Matrix ---
ax6 = axes[1, 2]
cm = confusion_matrix(y_te_nb, y_pred_nb)
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', ax=ax6,
            xticklabels=labels, yticklabels=labels)
ax6.set_title(f'Naive Bayes Confusion Matrix\n(Acc: {nb_acc*100:.1f}%)', fontweight='bold')
ax6.set_xlabel('Predicted')
ax6.set_ylabel('Actual')

