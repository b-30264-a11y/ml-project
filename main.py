r2_data.sort(key=lambda x: x[1])
names_r2 = [x[0].split('. ')[1] if '. ' in x[0] else x[0] for x in r2_data]
vals_r2  = [x[1] for x in r2_data]
colors_r2 = ['#e74c3c' if v < 0.7 else '#f39c12' if v < 0.85 else '#27ae60' for v in vals_r2]
bars = ax1.barh(names_r2, vals_r2, color=colors_r2, edgecolor='white', linewidth=0.5)
ax1.set_xlabel('R² Score')
