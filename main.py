import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings('ignore')

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.metrics import (mean_absolute_error, mean_squared_error,
                             r2_score, accuracy_score, classification_report,
                             confusion_matrix)

# Regression Models
from sklearn.linear_model import LinearRegression, Ridge, Lasso
from sklearn.tree import DecisionTreeRegressor, DecisionTreeClassifier
from sklearn.neighbors import KNeighborsRegressor, KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVR
from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor

import pickle


# ============================================================
# STEP 1: LOAD DATASET
# ============================================================
print("=" * 60)
print("STEP 1: LOADING DATASET")
print("=" * 60)

# ----------------------------------------------------------
# HOW TO UPLOAD DATA:
# Place 'car_data.csv' in the SAME FOLDER as this Python file.
# Download from: https://www.kaggle.com/datasets/vijayaadithyanvg/car-price-predictionused-cars
# ----------------------------------------------------------

df = pd.read_csv('../data/car_data.csv')

print(f"Dataset Shape: {df.shape}")
print(f"\nFirst 5 Rows:\n{df.head()}")
print(f"\nColumn Names: {list(df.columns)}")
print(f"\nData Types:\n{df.dtypes}")
print(f"\nMissing Values:\n{df.isnull().sum()}")
print(f"\nBasic Statistics:\n{df.describe()}")


# ============================================================
# STEP 2: DATA PREPROCESSING
# ============================================================

print("\n" + "=" * 60)
print("STEP 2: DATA PREPROCESSING")
print("=" * 60)

# Drop Car_Name column
if 'Car_Name' in df.columns:
    df.drop(columns=['Car_Name'], inplace=True)

# Create Car_Age feature
current_year = 2024

if 'Year' in df.columns:
    df['Car_Age'] = current_year - df['Year']
    df.drop(columns=['Year'], inplace=True)

# Remove duplicates
before = df.shape[0]

df.drop_duplicates(inplace=True)

print(f"Removed {before - df.shape[0]} duplicate rows")

# Remove missing values
df.dropna(inplace=True)

print(f"Dataset after cleaning: {df.shape}")

# ============================================================
# ENCODE ALL CATEGORICAL COLUMNS
# ============================================================

from sklearn.preprocessing import LabelEncoder

le = LabelEncoder()

# Automatically detect text columns
categorical_cols = df.select_dtypes(include=['object']).columns

print("\nCategorical Columns:", list(categorical_cols))

# Convert text columns into numbers
for col in categorical_cols:
    df[col] = le.fit_transform(df[col])
    print(f"Encoded '{col}'")

print("\nPreprocessed Data Sample:")
print(df.head())


# ============================================================
# STEP 3: DEFINE FEATURES AND TARGET
# ============================================================

print("\n" + "=" * 60)
print("STEP 3: FEATURE & TARGET DEFINITION")
print("=" * 60)

# CHECK COLUMN NAMES
print("\nDataset Columns:")
print(df.columns)

# TARGET COLUMN
target_col = 'Selling_Price'

# Features and Target
X = df.drop(columns=[target_col])

y = df[target_col]

print(f"\nFeatures (X): {list(X.columns)}")

print(f"\nTarget (y): {target_col}")

print(f"\nX shape: {X.shape}")

print(f"y shape: {y.shape}")

# ============================================================
# STEP 4: FEATURE SCALING
# ============================================================
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Save scaler for API use
with open('scaler.pkl', 'wb') as f:
    pickle.dump(scaler, f)
print("\nScaler saved as scaler.pkl")


# ============================================================
# STEP 5: TRAIN/TEST SPLIT (80% Train, 20% Test)
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42
)
print(f"\nTraining size: {X_train.shape[0]} rows")
print(f"Testing size:  {X_test.shape[0]} rows")


# ============================================================
# STEP 6: TRAIN ALL MODELS
# ============================================================
print("\n" + "=" * 60)
print("STEP 6: MODEL TRAINING")
print("=" * 60)

models = {
    # 1. Simple Linear Regression (using only 1 feature: Present_Price)
    "1. Simple Linear Regression": LinearRegression(),

    # 2. Multiple Linear Regression (all features)
    "2. Multiple Linear Regression": LinearRegression(),

    # 3. Ridge Regression (Non-linear regularization)
    "3. Ridge Regression (Non-Linear)": Ridge(alpha=1.0),

    # 4. Lasso Regression
    "4. Lasso Regression": Lasso(alpha=0.1),

    # 5. Decision Tree Regressor
    "5. Decision Tree": DecisionTreeRegressor(max_depth=6, random_state=42),

    # 6. K-Nearest Neighbors
    "6. KNN": KNeighborsRegressor(n_neighbors=5),

    # 7. Random Forest
    "7. Random Forest": RandomForestRegressor(n_estimators=100, random_state=42),

    # 8. Gradient Boosting
    "8. Gradient Boosting": GradientBoostingRegressor(n_estimators=100, random_state=42),

    # 9. SVR
    "9. SVR": SVR(kernel='rbf'),
}

results = {}

for name, model in models.items():
    if name == "1. Simple Linear Regression":
        # Use only 1 feature (index 0 = Present_Price after encoding)
        X_tr_simple = X_train[:, 0].reshape(-1, 1)
        X_te_simple = X_test[:, 0].reshape(-1, 1)
        model.fit(X_tr_simple, y_train)
        y_pred = model.predict(X_te_simple)
    else:
        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)

    mae  = mean_absolute_error(y_test, y_pred)
    mse  = mean_squared_error(y_test, y_pred)
    rmse = np.sqrt(mse)
    r2   = r2_score(y_test, y_pred)

    results[name] = {
        'model':  model,
        'y_pred': y_pred,
        'MAE':    round(mae, 4),
        'MSE':    round(mse, 4),
        'RMSE':   round(rmse, 4),
        'R2':     round(r2, 4),
    }
    print(f"\n{name}")
    print(f"  MAE={mae:.4f}  RMSE={rmse:.4f}  R²={r2:.4f}")


# ============================================================
# STEP 7: NAIVE BAYES (Classification Version)
# ============================================================
print("\n" + "=" * 60)
print("STEP 7: NAIVE BAYES (Classified Price Ranges)")
print("=" * 60)

# Convert price to categories for Naive Bayes (classification only)
bins   = [0, 3, 7, 15, 100]
labels = ['Low', 'Medium', 'High', 'Luxury']
y_cat  = pd.cut(y, bins=bins, labels=labels)
y_cat_encoded = LabelEncoder().fit_transform(y_cat)

X_tr_nb, X_te_nb, y_tr_nb, y_te_nb = train_test_split(
    X_scaled, y_cat_encoded, test_size=0.2, random_state=42
)

nb_model = GaussianNB()
nb_model.fit(X_tr_nb, y_tr_nb)
y_pred_nb = nb_model.predict(X_te_nb)

nb_acc = accuracy_score(y_te_nb, y_pred_nb)
print(f"Naive Bayes Accuracy: {nb_acc * 100:.2f}%")
print(f"\nClassification Report:\n{classification_report(y_te_nb, y_pred_nb, target_names=labels)}")

# Save NB for confusion matrix
results['10. Naive Bayes (Classification)'] = {
    'model': nb_model,
    'y_pred_nb': y_pred_nb,
    'accuracy': round(nb_acc * 100, 2)
}


# ============================================================
# STEP 8: LOGISTIC REGRESSION (Classification Version)
# ============================================================
print("\n" + "=" * 60)
print("STEP 8: LOGISTIC REGRESSION (Price Category Classification)")
print("=" * 60)

from sklearn.linear_model import LogisticRegression

lr_model = LogisticRegression(max_iter=1000, random_state=42)
lr_model.fit(X_tr_nb, y_tr_nb)
y_pred_lr = lr_model.predict(X_te_nb)

lr_acc = accuracy_score(y_te_nb, y_pred_lr)
print(f"Logistic Regression Accuracy: {lr_acc * 100:.2f}%")
print(f"\nClassification Report:\n{classification_report(y_te_nb, y_pred_lr, target_names=labels)}")

results['11. Logistic Regression (Classification)'] = {
    'model':    lr_model,
    'y_pred_lr': y_pred_lr,
    'accuracy': round(lr_acc * 100, 2)
}


# ============================================================
# STEP 9: RESULTS SUMMARY TABLE
# ============================================================
print("\n" + "=" * 60)
print("STEP 9: RESULTS SUMMARY (Regression Models)")
print("=" * 60)

summary_rows = []
for name, res in results.items():
    if 'R2' in res:
        summary_rows.append({
            'Model':  name,
            'MAE':    res['MAE'],
            'RMSE':   res['RMSE'],
            'R2':     res['R2'],
        })

summary_df = pd.DataFrame(summary_rows).sort_values('R2', ascending=False)
print(summary_df.to_string(index=False))


# ============================================================
# STEP 10: BEST MODEL SELECTION
# ============================================================
print("\n" + "=" * 60)
print("STEP 10: BEST MODEL SELECTION")
print("=" * 60)

best_row  = summary_df.iloc[0]
best_name = best_row['Model']
best_model_obj = results[best_name]['model']

print(f"Best Model: {best_name}")
print(f"R² Score  : {best_row['R2']}")
print(f"RMSE      : {best_row['RMSE']}")
print(f"MAE       : {best_row['MAE']}")

# Save best model
with open('best_model.pkl', 'wb') as f:
    pickle.dump(best_model_obj, f)
print("\n✅ best_model.pkl saved successfully!")


# ============================================================
# STEP 11: GRAPHICAL ANALYSIS
# ============================================================
print("\n" + "=" * 60)
print("STEP 11: GRAPHICAL ANALYSIS")
print("=" * 60)

fig, axes = plt.subplots(2, 3, figsize=(18, 12))
fig.suptitle('Car Price Prediction - Model Evaluation Graphs', fontsize=16, fontweight='bold')

# --- Graph 1: R² Score Comparison ---
ax1 = axes[0, 0]
