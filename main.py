ax1.set_xlim(0, 1.05)
for bar, val in zip(bars, vals_r2):
    ax1.text(bar.get_width() + 0.01, bar.get_y() + bar.get_height()/2,
             f'{val:.3f}', va='center', fontsize=8)
ax1.axvline(x=0.9, color='blue', linestyle='--', alpha=0.5, label='90% target')
ax1.legend(fontsize=8)

# --- Graph 2: RMSE Comparison ---
ax2 = axes[0, 1]
rmse_data = [(n, r['RMSE']) for n, r in results.items() if 'RMSE' in r]
names_rmse = [x[0].split('. ')[1] if '. ' in x[0] else x[0] for x in rmse_data]
vals_rmse  = [x[1] for x in rmse_data]
ax2.bar(range(len(names_rmse)), vals_rmse, color='#3498db', edgecolor='white')
ax2.set_xticks(range(len(names_rmse)))
