ax2.set_ylabel('RMSE (Lakhs)')
ax2.set_title('RMSE Comparison', fontweight='bold')
for i, v in enumerate(vals_rmse):
    ax2.text(i, v + 0.02, f'{v:.2f}', ha='center', fontsize=7)

# --- Graph 3: Actual vs Predicted (Best Model) ---
ax3 = axes[0, 2]
best_preds = results[best_name]['y_pred']
ax3.scatter(y_test, best_preds, alpha=0.6, color='#9b59b6', s=30, label='Predictions')
min_val = min(y_test.min(), best_preds.min())
max_val = max(y_test.max(), best_preds.max())
ax3.plot([min_val, max_val], [min_val, max_val], 'r--', lw=2, label='Perfect Fit')
ax3.set_xlabel('Actual Price (Lakhs)')
ax3.set_ylabel('Predicted Price (Lakhs)')
ax3.set_title(f'Actual vs Predicted\n({best_name.split(". ")[1]})', fontweight='bold')
ax3.legend()

# --- Graph 4: Residual Plot ---
ax4 = axes[1, 0]
residuals = y_test.values - best_preds
ax4.scatter(best_preds, residuals, alpha=0.6, color='#e67e22', s=30)
ax4.axhline(y=0, color='red', linestyle='--', lw=2)
ax4.set_xlabel('Predicted Price')
ax4.set_ylabel('Residuals')
ax4.set_title('Residual Plot (Best Model)', fontweight='bold')

# --- Graph 5: Error Distribution ---
ax5 = axes[1, 1]
